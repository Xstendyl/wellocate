#!/usr/bin/env python3
"""Write results/B11_SUMMARY.md, the summary of the PPO runs, from results/b11_test_A.json, b11_test_B.json and
b11_curves.json. The adaptation line is decided by comparing intervals.

Usage: python3 wellocate/examples/ppo_summary.py      (writes results/B11_SUMMARY.md)
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RES = os.path.join(ROOT, "results")
RUNS = (("A", "grid train only", "nk:test", ("gb1:test", "phoq:test")), ("B", "grid + GB1 train", None, ("phoq:test",)))


def ci(x, f="%.3f"):
    return "[%s, %s]" % (f % x[0], f % x[1])


def overlaps(a, b):
    return a[0] <= b[1] and b[0] <= a[1]


def render():
    tests = {r: json.load(open(os.path.join(RES, "b11_test_%s.json" % r))) for r, *_x in RUNS}
    curves = json.load(open(os.path.join(RES, "b11_curves.json")))
    out = ["# B11 summary: a small PPO policy trained through Wellocate's released interface", "",
           "Generated by `wellocate/examples/ppo_summary.py` from `results/b11_test_A.json`, `results/b11_test_B.json` "
           "and `results/b11_curves.json`. Pre-registration: `spec/B11_PREREGISTRATION.md`. Each run trained three "
           "seeds and was tested once, on all 1,500 episodes of each test split.", "",
           "## Registered outcome", "",
           "Trained minus each comparator, paired by test episode, mean over three seeds with a 95% interval; a "
           "criterion holds when the interval lies above zero and every seed is positive.", "",
           "| run | trained on | test split | role | vs its initialisation | vs random ordering | holds |",
           "|---|---|---|---|---|---|---|"]
    for r, trained_on, learn, transfer in RUNS:
        for sp in ([learn] if learn else []) + list(transfer):
            c = tests[r]["splits"][sp]["comparisons"]
            i, rnd = c["vs initialisation"], c["vs random"]
            role = "learnable" if sp == learn else "transfer"
            out.append("| %s | %s | %s | %s | %+.3f %s | %+.3f %s | %s |" % (
                r, trained_on, sp, role, i["mean"], ci(i["ci"]), rnd["mean"], ci(rnd["ci"]),
                "yes" if i["holds"] and rnd["holds"] else "no (vs random: seeds %s)" % ", ".join(
                    "%+.3f" % x for x in rnd["per_seed"]) if not rnd["holds"] else "no"))
    out += ["", "## Selected checkpoints", "", "| run | seed | selected update | validation score | SHA-256 (first 16) |",
            "|---|---|---|---|---|"]
    for r, *_x in RUNS:
        for c in tests[r]["checkpoints"]:
            out.append("| %s | %d | %d | %.4f | `%s` |" % (r, c["seed"], c["best_update"], c["best_score"],
                                                        c["best_sha256"][:16]))
    out += ["", "## Against the scripted policies (reported; the registration does not require it)", "",
            "| run | test split | trained pick | guessing | informed | model-guided | trained minus guessing | "
            "minus informed | minus model-guided |", "|---|---|---|---|---|---|---|---|---|"]
    for r, _t, learn, transfer in RUNS:
        for sp in ([learn] if learn else []) + list(transfer):
            s = tests[r]["splits"][sp]
            v = s["versus_scripted"]
            pick = lambda n: s["scripted"][n]["pick"]["mean"]
            out.append("| %s | %s | %.3f | %.3f | %.3f | %.3f | %+.3f %s | %+.3f %s | %+.3f %s |" % (
                r, sp, s["table"]["trained"]["pick"]["mean"], pick("guessing"), pick("informed"), pick("model-guided"),
                v["guessing"]["mean"], ci(v["guessing"]["ci"]), v["informed"]["mean"], ci(v["informed"]["ci"]),
                v["model-guided"]["mean"], ci(v["model-guided"]["ci"])))
    a = tests["A"]["splits"]
    g = a["nk:test"]["table"]["trained"]["share"]
    prot = [(sp, a[sp]["table"]["trained"]["share"]) for sp in ("gb1:test", "phoq:test")]
    adapt = not any(overlaps(g["ci_two_level"], p["ci_two_level"]) for _sp, p in prot)
    out += ["", "## Re-testing across landscapes", "",
            "Run A's re-testing share %s across landscapes: grid %.1f%% %s %s the protein intervals (%s)." % (
                "differs" if adapt else "does not adapt", g["mean"], ci(g["ci_two_level"], "%.1f"),
                "separates from" if adapt else "overlaps",
                "; ".join("%s %.1f%% %s" % (sp.split(":")[0].upper() if sp.startswith("gb1") else "PhoQ", p["mean"],
                                            ci(p["ci_two_level"], "%.1f")) for sp, p in prot)), "",
            "Best scripted policy's share on the same test episodes: " + "; ".join(
                "%s %s %.1f%%" % (sp, s["best_scripted_on_test"]["policy"], s["best_scripted_on_test"]["share"])
                for sp, s in a.items()) + ".", "",
            "## Training", "",
            "| run | seed | episodes | wall clock | validation score at update 0 | at the selected update | at update 1,500 |",
            "|---|---|---|---|---|---|---|"]
    for r, *_x in RUNS:
        for c in tests[r]["checkpoints"]:
            pts = {p["update"]: p for p in curves["%s_s%d" % (r, c["seed"])]["points"]}
            out.append("| %s | %d | %d | %.2f h | %.3f | %.3f | %.3f |" % (
                r, c["seed"], c["episodes"], c["wall_s"] / 3600, pts[0]["val_score"], pts[c["best_update"]]["val_score"],
                pts[1500]["val_score"]))
    return "\n".join(out) + "\n"


def main():
    with open(os.path.join(RES, "B11_SUMMARY.md"), "w") as f:
        f.write(render())
    print("wrote results/B11_SUMMARY.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
