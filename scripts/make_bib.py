def esc(s):
    """Protect capitals inside a title, which BibTeX would otherwise lowercase."""
    return re.sub(r"\b([A-Z]{2,}|[A-Z][a-z]*[A-Z][\w-]*)\b", r"{\1}", s)


def render():
    rec = json.load(open(os.path.join(ROOT, "results", "citations_verified.json")))
    by = {(e.get("arxiv") or e.get("doi")): e for e in rec}
    out = ["% Generated by scripts/make_bib.py from results/citations_verified.json.",
           "% Every field comes from arXiv's own API. Do not edit by hand; regenerate.", ""]
    missing = []
    for aid, key in KEYS.items():
        e = by.get(aid)
        if not e:
            missing.append(aid)
            continue
        authors = " and ".join(e.get("authors") or []) or "Unknown"
        v = VENUES.get(key, {})
        out.append("@%s{%s," % ("inproceedings" if v else "article", key))
        out.append("  author       = {%s}," % authors)
        out.append("  title        = {%s}," % esc(e.get("title") or ""))
        # A published venue is the booktitle. The arXiv id stays in eprint, so a reader sees where the paper
        # appeared and can still find the preprint.
        if v:
            out.append("  booktitle    = {%s}," % v["booktitle"])
        else:
            out.append("  journal      = {arXiv preprint arXiv:%s}," % aid.split("v")[0])
        for f in ("volume", "pages"):
            if f in v:
                out.append("  %-12s = {%s}," % (f, v[f]))
        out.append("  year         = {%s}," % v.get("year", (e.get("published") or "")[:4]))
        for f in ("doi", "url"):
            if f in v:
                out.append("  %-12s = {%s}," % (f, v[f]))
        out.append("  eprint       = {%s}," % aid.split("v")[0])
        out.append("  archiveprefix = {arXiv}")
        out.append("}")
        out.append("")
    for doi, key in DOI_KEYS.items():
        e = by.get(doi)
        if not e:
            missing.append(doi)
            continue
        pages = e.get("page")
        if not pages and (e.get("container") or "").strip().lower() == "elife":
            # eLife numbers articles instead of paginating; the article number is the DOI's suffix.
            pages = "e%s" % doi.rsplit(".", 1)[-1]
        out.append("@article{%s," % key)
        out.append("  author       = {%s}," % " and ".join(e.get("authors") or []))
        out.append("  title        = {%s}," % esc(e.get("title") or ""))
        out.append("  journal      = {%s}," % (e.get("container") or ""))
        out.append("  year         = {%s}," % e.get("year"))
        if e.get("volume"):
            out.append("  volume       = {%s}," % e["volume"])
        if e.get("issue"):
            out.append("  number       = {%s}," % e["issue"])
        if pages:
            out.append("  pages        = {%s}," % pages.replace("-", "--"))
        out.append("  doi          = {%s}" % doi)
        out.append("}")
        out.append("")
    if missing:
        raise SystemExit("REFUSED: no verified record for %s. Run verify_citations.py first."
                         % ", ".join(missing))
    return "\n".join(out) + EXTRA


DST = os.path.join(ROOT, "paper", "refs.bib")


def main(argv=None):
    # Writes paper/ only with --write-paper (scripts/paper_write.py); any other argument is refused.
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import paper_write as PW
    return PW.run(__file__, DST, render, argv)


if __name__ == "__main__":
    sys.exit(main())
