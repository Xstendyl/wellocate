#!/usr/bin/env python3
"""Render the table of attractor basins per model and arm from results/basins.json (scripts/basins.py).

The table is not part of the paper. The script prints it, or writes it with --out to a path outside paper/.

  python3 scripts/make_table_basins.py [--out PATH]
"""
import argparse, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ORDER = ["Opus 4.7", "Gemini 2.5 Flash", "DeepSeek V3.1", "GPT-6.1 Sol", "Gemini 3.1 Pro"]


def render():
    b = json.load(open(os.path.join(ROOT, "results", "basins.json")))
    out = ["% Generated by scripts/make_table_basins.py from results/basins.json. Not part of the paper.",
           "\\begin{table}[!htbp]", "\\centering", "\\small",
           "\\caption{Attractor basins per model and arm. \\emph{Start's basin}: the share of campaigns whose nominee lies "
           "in the basin of the starting variant. \\emph{Basin peak}: the mean value of the nominee's basin peak (the "
           "global peak is %.3f on both landscapes). \\emph{Basins}: distinct basins among the variants measured. The "
           "scripted rules run on our reference seeds at their best k. Descriptive: arms differ in landscape, "
           "seeds and run.}" % b["landscapes"]["grid"]["global_peak_value"],
           "\\label{tab:basins}",
           "\\begin{tabular}{llrrrrr}", "\\toprule",
           "arm & model & campaigns & pick & start's basin, \\% & basin peak & basins \\\\", "\\midrule"]
    arms = list(b["arms"])
    for j, arm in enumerate(arms):
        rows = [(m, b["arms"][arm][m]) for m in ORDER]
        land = "grid" if arm.startswith("grid") else "GB1"
        if arm.endswith("Blind"):
            rows += list(b["scripted"][land].items())
        for i, (m, d) in enumerate(rows):
            out.append("%s & %s & %d & %.2f & %.0f & %.3f & %.1f \\\\" % (
                arm if i == 0 else "", m, d["n"], d["nominee_value"], 100 * d["nominee_in_start_basin"],
                d["nominee_basin_peak"], d["distinct_basins"]))
        if j < len(arms) - 1:
            out.append("\\midrule")
    out += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    return "\n".join(out) + "\n"


def main(argv=None):
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import paper_write as PW
    ap = argparse.ArgumentParser(description="Render the basins table; nothing is written into paper/.")
    ap.add_argument("--out", default="", help="write the table to this path (never inside paper/)")
    a = ap.parse_args(sys.argv[1:] if argv is None else argv)
    text = render()
    if not a.out:
        sys.stdout.write(text)
        return 0
    if PW.inside_paper(a.out):
        ap.error("--out %s is inside paper/; the basins table is not part of the paper" % a.out)
    with open(a.out, "w") as f:
        f.write(text)
    print("wrote %s" % a.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
