#!/usr/bin/env python3
"""Write paper/sections/table_splits.tex, the benchmark's split table, from wellocate/splits.json.

  python3 scripts/make_table_splits.py

scripts/verify_paper_numbers.py fails if the copy in paper/ differs from a fresh render.
"""
import os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from wellocate import splits as SP                                   # noqa: E402

DST = os.path.join(ROOT, "paper", "sections", "table_splits.tex")
FAMILIES = [("gb1", "scrambled GB1", "protein"), ("phoq", "scrambled PhoQ", "protein"), ("nk", "generated NK", "grid")]
COLS = [("train", "train"), ("validation", "validation"), ("test", "test"),
        ("held out", ("transfer_real", "test_ood_k2", "test_ood_k3")), ("paper", "paper")]


def render():
    sp = SP.load()["splits"]
    out = ["% Generated by scripts/make_table_splits.py from wellocate/splits.json. Do not edit by hand;",
           "% scripts/verify_paper_numbers.py regenerates it and fails on any difference.",
           "\\begin{table}[!htbp]", "\\centering", "\\small",
           # A 5pt column half-gap fits seven columns in the text width; scoped to this table.
           "\\setlength{\\tabcolsep}{5pt}",
           "\\caption{Wellocate's frozen splits: landscapes / episodes per split. Train, validation and test use "
           "disjoint landscape seeds (scrambles for GB1 and PhoQ, NK seeds for the grid) and disjoint campaign seeds. "
           "Held out: the real amino-acid names for GB1 and PhoQ, and two rougher NK settings, $K = 2$ and $K = 3$. "
           "\\emph{Paper} is the landscape and seeds used in this study.}",
           "\\label{tab:splits}",
           "\\begin{tabular}{llrrrrr}", "\\toprule",
           "track & landscape & " + " & ".join(c for c, _k in COLS) + " \\\\", "\\midrule"]
    for fam, label, track in FAMILIES:
        cells = []
        for _c, keys in COLS:
            keys = (keys,) if isinstance(keys, str) else keys
            got = [sp["%s:%s" % (fam, k)] for k in keys if "%s:%s" % (fam, k) in sp]
            txt = ["%d / %s" % (len(e["instances"]), "{:,}".format(e["episodes"]).replace(",", "{,}")) for e in got]
            if len(txt) > 1:
                # Several held-out sets share one cell: one per line, each named by its K.
                names = [k for k in keys if "%s:%s" % (fam, k) in sp]
                txt = ["$K = %s$: %s" % (n[-1], t) for n, t in zip(names, txt)]
                cells.append("\\begin{tabular}[t]{@{}r@{}}" + " \\\\ ".join(txt) + "\\end{tabular}")
            else:
                cells.append(txt[0] if txt else "--")
        out.append("%s & %s & %s \\\\" % (track, label, " & ".join(cells)))
    out += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    return "\n".join(out) + "\n"


def main(argv=None):
    # Writes paper/ only with --write-paper (scripts/paper_write.py); any other argument is refused.
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import paper_write as PW
    return PW.run(__file__, DST, render, argv)


if __name__ == "__main__":
    sys.exit(main())
