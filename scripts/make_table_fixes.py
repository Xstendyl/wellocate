#!/usr/bin/env python3
"""Write paper/sections/table_fixes.tex, the main text's table of what each tool does, from results/findings.json.

Every value is a findings headline. scripts/verify_paper_numbers.py regenerates this table and fails if the copy
in paper/ differs.

Usage: python3 scripts/make_table_fixes.py
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import make_paper_numbers as MPN                                     # noqa: E402

DST = os.path.join(ROOT, "paper", "sections", "table_fixes.tex")
P0, P3, P5 = "0an panel (F0, F1, F2)", "0an.3 F5 structure", "0an.5 Opus menu top-up"
# model: the change in re-testing share on the grid with the ledger, the landscape note (the structure arm) and
# the Menu. The Menu's effect on scrambled GB1, and the GPT-6.1 Sol and Gemini 3.1 Pro arms, are in Figure 5.
ROWS = [("Opus 4.7", (P0, "F1 Opus share change, points"), (P3, "F5 Opus share change, points"),
         (P5, "Opus share change at n = 60, points")),
        ("Gemini 2.5 Flash", (P0, "F1 Gemini share change, points"), (P3, "F5 Gemini share change, points"),
         (P0, "F2 Gemini share change, points")),
        ("DeepSeek V3.1", (P0, "F1 DeepSeek share change, points"), (P3, "F5 DeepSeek share change, points"),
         (P0, "F2 DeepSeek share change, points"))]


def render():
    rows = {r["id"]: r for r in json.load(open(os.path.join(ROOT, "results", "findings.json")))["rows"]}
    out = ["% Generated by scripts/make_table_fixes.py from results/findings.json. Do not edit by hand;",
           "% scripts/verify_paper_numbers.py regenerates it and fails on any difference.",
           "\\begin{table}[!htbp]", "\\centering", "\\footnotesize",
           "\\caption{Change in re-testing share on the grid when each aid is added, in percentage points against the "
           "same model's control on the same seeds, with 95\\% intervals. Negative values mean less re-testing. The "
           "Menu's effect on scrambled GB1 is in Figure~\\ref{fig:fixes}.}",
           "\\label{tab:fixes}",
           "\\begin{tabular}{lrrr}", "\\toprule",
           "model & ledger & landscape note & Menu \\\\", "\\midrule"]
    for name, *cells in ROWS:
        shown = []
        for c in cells:
            h = MPN.lookup(rows, *c)
            shown.append("%s [%s, %s]" % (MPN.fmt(h["value"], "s1"), MPN.fmt(h["ci"][0], "s1"), MPN.fmt(h["ci"][1], "s1")))
        out.append("%s & %s \\\\" % (name, " & ".join(shown)))
    out += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    return "\n".join(out) + "\n"


def main(argv=None):
    # Writes paper/ only with --write-paper (scripts/paper_write.py); any other argument is refused.
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import paper_write as PW
    return PW.run(__file__, DST, render, argv)


if __name__ == "__main__":
    sys.exit(main())
