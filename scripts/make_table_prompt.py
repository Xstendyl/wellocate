#!/usr/bin/env python3
"""Write paper/sections/table_prompt.tex, the prompt-check table, from results/analysis_0al.json.

One row per prompt-check cell. The grid column is the original campaigns on the same seeds, so every column is
compared on identical noise draws. scripts/verify_paper_numbers.py regenerates this file and fails if the copy in
paper/ differs.

Usage: python3 scripts/make_table_prompt.py
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import figstyle as FS                                                  # noqa: E402

DST = os.path.join(ROOT, "paper", "sections", "table_prompt.tex")
CONDITIONS = ("Blind", "Mechanism")


def render():
    a = FS.results("analysis_0al.json")
    A, B, drift = a["panel_A"]["cells"], a["panel_B"]["cells"], a["panel_A0"]["drift_vs_grid"]["cells"]
    lines = [
        "% Generated by scripts/make_table_prompt.py from results/analysis_0al.json.",
        "% Do not edit by hand; verify_paper_numbers.py regenerates it and fails on any difference.",
        "\\begin{table}[tbp]",
        "\\centering",
        "\\small",
        "\\caption{Re-testing share in the prompt checks, as a percentage of used slots, on the same 60 seeds "
        "in every column. \\emph{Grid} is the original campaigns on those seeds. Check~A states that the final "
        "pick is scored on its true value and corrects the replacement prompt's order count. Check~B also makes "
        "a rejected order free. \\emph{Same-day rerun minus grid} is the change, in points, for the original "
        "prompts run again on the same day as check~A.}",
        "\\label{tab:prompt}",
        "\\begin{tabular}{llrrrr}",
        "\\toprule",
        "model & condition & grid & check A & check B & same-day rerun minus grid \\\\",
        "\\midrule",
    ]
    for i, (key, label, _c, _m) in enumerate(FS.MODELS):
        short = key.split("/")[-1]
        if i:
            lines.append("\\addlinespace")
        for j, cond in enumerate(CONDITIONS):
            k = "%s|%s" % (cond, short)
            lines.append("%s & %s & %.1f & %.1f & %.1f & $%+.1f$ \\\\" % (
                label if j == 0 else "", cond, A[k]["share_old_paired"], A[k]["share_new"],
                B[k]["share_new"], drift[k]["d_share"]))
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines)


def main(argv=None):
    # Writes paper/ only with --write-paper (scripts/paper_write.py); any other argument is refused.
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import paper_write as PW
    return PW.run(__file__, DST, render, argv)


if __name__ == "__main__":
    sys.exit(main())
