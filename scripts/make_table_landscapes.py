#!/usr/bin/env python3
"""Write paper/sections/table_landscapes.tex: each model's re-testing share and final pick on the grid, GB1 and PhoQ,
with the three scripted rules at their best setting.

  python3 scripts/make_table_landscapes.py --write-paper

Model numbers come from results/landscapes_0an8.json and scripted-rule numbers from results/scripted_rules_best.json,
both via scripts/findings.py. On each landscape the highest pick is set in bold, decided on unrounded values.
scripts/verify_paper_numbers.py fails if this file differs from render().
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import make_paper_numbers as MPN                                     # noqa: E402

DST = os.path.join(ROOT, "paper", "sections", "table_landscapes.tex")
ROW = "0an.8 descriptive: three landscapes side by side"
RULES_ROW = "scripted rules at their best setting: Table 1's rows"
ORDER = ["Opus 4.7", "Gemini 2.5 Flash", "DeepSeek V3.1", "GPT-6.1 Sol", "Gemini 3.1 Pro"]
LANDS = ["grid", "GB1", "PhoQ"]
RULES = ["guessing", "informed", "model-guided"]


def render():
    rows = {r["id"]: r for r in json.load(open(os.path.join(ROOT, "results", "findings.json")))["rows"]}
    raw = lambda row, name: MPN.lookup(rows, row, name)["value"]
    v = lambda name, f, row=ROW: MPN.fmt(raw(row, name), f)
    out = ["% Generated by scripts/make_table_landscapes.py from results/findings.json (results/landscapes_0an8.json and",
           "% results/scripted_rules_best.json). Do not edit by hand; scripts/verify_paper_numbers.py regenerates it and",
           "% fails on any difference.",
           "\\begin{table}[tbp]", "\\centering", "\\small",
           "\\caption{Re-testing share and true value of the final pick on each landscape, averaged over each model's "
           "campaigns. The three scripted rules are shown at their best setting.}",
           "\\label{tab:landscapes}",
           "\\begin{tabular}{lrrrrrr}", "\\toprule",
           " & \\multicolumn{2}{c}{grid} & \\multicolumn{2}{c}{GB1} & \\multicolumn{2}{c}{PhoQ} \\\\",
           "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}",
           " & share (\\%) & pick & share (\\%) & pick & share (\\%) & pick \\\\", "\\midrule"]
    for name in ORDER:
        cells = []
        for land in LANDS:
            cells += [v("%s, %s, re-testing share, %%" % (land, name), "f1"), v("%s, %s, final pick" % (land, name), "f2")]
        out.append("%s & %s \\\\" % (name, " & ".join(cells)))
    out.append("\\midrule")
    pick = lambda land, r: raw(RULES_ROW, "%s, %s rule, final pick" % (land, r))
    top = {land: max(RULES, key=lambda r: pick(land, r)) for land in LANDS}
    for r in RULES:
        cells = []
        for land in LANDS:
            p = v("%s, %s rule, final pick" % (land, r), "f2", RULES_ROW)
            cells += [v("%s, %s rule, re-testing share, %%" % (land, r), "f1", RULES_ROW),
                      "\\textbf{%s}" % p if top[land] == r else p]
        out.append("%s rule & %s \\\\" % (r, " & ".join(cells)))
    out += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    return "\n".join(out) + "\n"


def main(argv=None):
    # Writes paper/ only with --write-paper (scripts/paper_write.py); any other argument is refused.
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import paper_write as PW
    return PW.run(__file__, DST, render, argv)


if __name__ == "__main__":
    sys.exit(main())
