#!/usr/bin/env python3
"""Write paper/sections/table_cells.tex, the per-cell results table, from the analysis output.

  python3 scripts/make_table_cells.py

The table is written from results/analysis_final/grid/summary.json, and scripts/verify_paper_numbers.py
regenerates it and fails if the file in paper/ differs.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import figstyle as FS                                                  # noqa: E402

DST = os.path.join(ROOT, "paper", "sections", "table_cells.tex")


def render():
    cells = {(x["condition"], x["model"]): x for x in FS.results(os.path.join(
        "analysis_final", "grid", "summary.json"))["cells_detail"]}
    vs = {(x["condition"], x["model"]): x for x in FS.results("loss_vs_guessing.json")["cells"]}
    ref = FS.refs()
    lines = [
        "% Generated by scripts/make_table_cells.py from results/analysis_final/grid/summary.json.",
        "% Do not edit by hand; verify_paper_numbers.py regenerates it and fails on any difference.",
        "\\begin{table}[tbp]",
        "\\centering",
        "\\small",
        "\\caption{Results for each cell, one model under one prompt condition. \\emph{Share} is the re-testing "
        "share, the fraction of used slots spent re-testing a candidate already ordered. \\emph{Excl.\\ start} "
        "leaves out re-orders of the start, whose reading the agent is given in advance. "
        "\\emph{Distinct} is the mean number of different candidates measured per campaign, and "
        "\\emph{pick} the mean true value of the final pick. The last three columns compare each cell "
        "with the guessing rule at its best setting, which measures %.2f distinct candidates and reaches "
        "%.2f. \\emph{Tested} is how much further the best candidate the agents measured falls short of the "
        "global best. \\emph{Picked} is the change in how far their pick falls short of the best they "
        "measured, negative where they picked better. \\emph{Net} is the sum, the agents' shortfall in the true "
        "value of the final pick; rounded parts may not add to it exactly.}"
        % (ref["fair_distinct"], ref["fair_kstar"]),
        "\\label{tab:cells}",
        "\\begin{tabular}{llrrrrrrr}",
        "\\toprule",
        " & & \\multicolumn{2}{c}{share (\\%)} & & & \\multicolumn{3}{c}{against the guessing rule} \\\\",
        "\\cmidrule(lr){3-4}\\cmidrule(lr){7-9}",
        "model & condition & all & excl.\\ start & distinct & pick & tested & picked & net \\\\",
        "\\midrule",
    ]
    for i, (key, label, _c, _m) in enumerate(FS.MODELS):
        short = key.split("/")[-1]
        if i:
            lines.append("\\addlinespace")
        for j, cond in enumerate(FS.CONDITIONS):
            x, v = cells[(cond, short)], vs[(cond, short)]
            lines.append("%s & %s & %.1f & %.1f & %.1f & %.2f & $%+.2f$ & $%+.2f$ & $%+.2f$ \\\\" % (
                label if j == 0 else "", cond,
                100 * x["replication"]["over slots used"], 100 * x["replication"]["excl anchor, slots used"],
                x["distinct"], x["mean"], v["extra_exploration"], v["selection_change"], v["net"]))
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines)


def main(argv=None):
    # Writes paper/ only with --write-paper (scripts/paper_write.py); any other argument is refused.
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import paper_write as PW
    return PW.run(__file__, DST, render, argv)


if __name__ == "__main__":
    sys.exit(main())
