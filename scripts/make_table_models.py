#!/usr/bin/env python3
"""Write paper/sections/table_models.tex, the main text's table of the five models as run.

  python3 scripts/make_table_models.py

Release month and reasoning setting come from each arm's run manifest (via results/paper_figdata.json), with
the median reasoning tokens per call. scripts/verify_paper_numbers.py regenerates this table and fails if the
copy in paper/ differs.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import make_paper_numbers as MPN                                     # noqa: E402

DST = os.path.join(ROOT, "paper", "sections", "table_models.tex")
ORDER = ["Opus 4.7", "Gemini 2.5 Flash", "DeepSeek V3.1", "GPT-6.1 Sol", "Gemini 3.1 Pro"]


def render():
    rows = {r["id"]: r for r in json.load(open(os.path.join(ROOT, "results", "findings.json")))["rows"]}
    fig = json.load(open(os.path.join(ROOT, "results", "paper_figdata.json")))["models"]
    out = ["% Generated by scripts/make_table_models.py from results/paper_figdata.json and results/findings.json.",
           "% Do not edit by hand; scripts/verify_paper_numbers.py regenerates it and fails on any difference.",
           "\\begin{table}[tbp]", "\\centering", "\\small",
           "\\caption{The five models as run on the grid. GPT-6.1 Sol and Gemini 3.1 Pro ran at their lowest "
           "reasoning setting. Reasoning tokens are the median over every logged call of the runs with the Blind "
           "prompt. Sol reported zero reasoning tokens on at least half of its calls.}",
           "\\label{tab:models}",
           "\\begin{tabular}{llll}", "\\toprule",
           "model & released & reasoning as run & median reasoning tokens per call \\\\", "\\midrule"]
    for name in ORDER:
        m = fig[name]
        med = MPN.lookup(rows, MPN.HEAD, "%s, median reasoning tokens per call" % name)["value"]
        setting = "off" if m["reasoning_effort"] is None else "%s" % m["reasoning_effort"]
        out.append("%s & %s & %s & %s \\\\" % (name, m["released"], setting, MPN.fmt(med, "f0")))
    out += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    return "\n".join(out) + "\n"


def main(argv=None):
    # Writes paper/ only with --write-paper (scripts/paper_write.py); any other argument is refused.
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import paper_write as PW
    return PW.run(__file__, DST, render, argv)


if __name__ == "__main__":
    sys.exit(main())
